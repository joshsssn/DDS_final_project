"""Phase 4.5 - bias check: how much do navigation templates inflate out-degree?

The dump's pagelinks table contains every link of the rendered page, including links
generated by navigation boxes ("palettes") and portal banners at the bottom of an
article. A player can click them, but they are not what people perceive as the
article's content. For a sample of pages we fetch the rendered HTML of the *exact
revision of the dump* (MediaWiki API, action=parse&oldid=page_latest) and count
distinct linked ARTICLES, resolving link titles exactly like clean.py does for the
dump (redirect titles -> final article, non-articles dropped, own page excluded):
    html_all   in the whole rendered HTML
    body       after removing navigation boxes and portal banners
and compare with the dump out-degree (same unit).

Removed elements (frwiki class names, checked on real pages):
    .navbox-container, .navbox, .navigation-only, #bandeau-portail, .bandeau-portail
Sample: top-`n_top_candidates` articles by out-degree, top-`n_top_in_degree` by in-degree
(general pages such as countries) and `n_random` random
non-disambiguation articles (seed in config.yaml).
Responses are cached in data/raw/api/ (re-runs make no requests); polite rate:
one request per `sleep_seconds`, maxlag=5, descriptive User-Agent.
"""
from __future__ import annotations

import time
from urllib.parse import unquote

import numpy as np
import pandas as pd
import requests
from bs4 import BeautifulSoup

from .common import get_logger, load_config, path, read_json, write_json

log = get_logger("bias_check")
API = "https://fr.wikipedia.org/w/api.php"
REMOVE = [".navbox-container", ".navbox", ".navigation-only", "#bandeau-portail", ".bandeau-portail"]


def api_get(session, params, cache_file, sleep):
    """GET the API with caching, honouring maxlag and HTTP 429 (Retry-After + backoff)."""
    if cache_file.exists():
        return read_json(cache_file)
    for attempt in range(8):
        r = session.get(API, params={**params, "format": "json", "formatversion": 2, "maxlag": 5},
                        timeout=120)
        if r.status_code == 429 or r.status_code >= 500:
            wait = float(r.headers.get("Retry-After", 0) or 0) or 30 * 2 ** attempt
            log.warning("HTTP %d, waiting %.0f s", r.status_code, wait)
            time.sleep(wait)
            continue
        r.raise_for_status()
        data = r.json()
        time.sleep(sleep)
        if data.get("error", {}).get("code") == "maxlag":
            time.sleep(5 * (attempt + 1))
            continue
        write_json(data, cache_file)
        return data
    raise RuntimeError("API kept refusing the request (429/maxlag)")


def namespace_prefixes(session, cache_dir, sleep) -> set[str]:
    """All namespace names and aliases except the main namespace (lower-cased)."""
    d = api_get(session, {"action": "query", "meta": "siteinfo",
                          "siprop": "namespaces|namespacealiases"},
                cache_dir / "siteinfo_namespaces.json", sleep)["query"]
    names = set()
    for ns in d["namespaces"].values():
        if ns["id"] != 0:
            names.update(n.lower() for n in (ns.get("name"), ns.get("canonical")) if n)
    names.update(a["alias"].lower() for a in d["namespacealiases"] if a["id"] != 0)
    return names


def ns0_link_titles(soup, prefixes) -> set[str]:
    """Distinct titles of links to existing namespace-0 pages in a parsed HTML tree."""
    out = set()
    for a in soup.find_all("a", href=True):
        href = a["href"]
        if not href.startswith("/wiki/") or "new" in (a.get("class") or []):
            continue  # external/interwiki links, or red links (class "new")
        title = unquote(href[len("/wiki/"):].split("#")[0]).replace(" ", "_")
        if not title:
            continue
        if ":" in title and title.split(":", 1)[0].replace("_", " ").lower() in prefixes:
            continue
        out.add(title)
    return out


def link_titles(html: str, prefixes) -> tuple[set[str], set[str], int]:
    """(titles in the whole page, titles outside navigation boxes, #removed elements)."""
    soup = BeautifulSoup(html, "html.parser")
    all_titles = ns0_link_titles(soup, prefixes)
    removed = 0
    for sel in REMOVE:
        for el in soup.select(sel):
            el.decompose()
            removed += 1
    return all_titles, ns0_link_titles(soup, prefixes), removed


def resolve_titles(cfg, titles: set[str]) -> dict[str, int]:
    """Map link titles to article page ids exactly as clean.py does for the dump:
    article titles map to themselves, redirect titles to their final article.
    Titles that are not (or do not lead to) articles are absent from the result."""
    import duckdb
    proc, interim = path(cfg, "processed"), path(cfg, "interim")
    con = duckdb.connect()
    con.register("t", pd.DataFrame({"title": sorted(titles)}))
    rows = con.execute(f"""
        SELECT t.title, CASE WHEN NOT p.page_is_redirect THEN p.page_id ELSE r.final_page_id END
        FROM t
        JOIN read_parquet('{(interim / "page.parquet").as_posix()}') p
          ON p.page_namespace = 0 AND p.page_title = t.title
        LEFT JOIN read_parquet('{(proc / "redirect_resolution.parquet").as_posix()}') r
          ON r.page_id = p.page_id""").fetchall()
    return {a: int(b) for a, b in rows if b is not None and b >= 0}


def main() -> None:
    cfg = load_config()
    B = cfg["bias_check"]
    if not B.get("enabled", True):
        log.info("bias check disabled in config.yaml: nothing to do")
        return
    cache = path(cfg, "api_cache")
    nodes = pd.read_parquet(path(cfg, "processed") / "graph" / "nodes.parquet")
    top = nodes.sort_values("out_degree", ascending=False, kind="stable").head(B["n_top_candidates"])
    rng = np.random.default_rng(B["seed"])
    elig = nodes[~nodes.is_disambig & ~nodes.node_id.isin(top.node_id)]
    rand = elig.iloc[rng.choice(len(elig), size=B["n_random"], replace=False)]
    # "general" pages players use as landmarks (countries...) have the highest in-degree
    top_in = (nodes[~nodes.node_id.isin(top.node_id) & ~nodes.node_id.isin(rand.node_id)]
              .sort_values("in_degree", ascending=False, kind="stable").head(B["n_top_in_degree"]))
    sample = pd.concat([top.assign(group="top_out_degree"), top_in.assign(group="top_in_degree"),
                        rand.assign(group="random")])

    session = requests.Session()
    session.headers["User-Agent"] = cfg["user_agent"]
    prefixes = namespace_prefixes(session, cache, B["sleep_seconds"])
    rows, found = [], []
    for k, r in enumerate(sample.itertuples(), 1):
        data = api_get(session, {"action": "parse", "oldid": int(r.page_latest), "prop": "text",
                                 "disablelimitreport": 1, "disableeditsection": 1},
                       cache / f"parse_{int(r.page_id)}_{int(r.page_latest)}.json", B["sleep_seconds"])
        if "error" in data:
            log.warning("%s: %s", r.title, data["error"].get("code"))
            rows.append({"page_id": r.page_id, "title": r.title, "group": r.group,
                         "dump_out_degree": r.out_degree, "error": data["error"].get("code")})
            continue
        all_t, body_t, removed = link_titles(data["parse"]["text"], prefixes)
        found.append((all_t, body_t))
        rows.append({"page_id": r.page_id, "title": r.title, "group": r.group,
                     "dump_out_degree": r.out_degree, "removed_elements": removed, "error": None,
                     "html_titles_raw": len(all_t)})
        if k % 25 == 0:
            log.info("%d / %d pages", k, len(sample))
    # count distinct linked ARTICLES (redirects resolved, own page excluded), like the dump
    title_map = resolve_titles(cfg, set().union(*(a for a, _ in found)))
    it = iter(found)
    for row in rows:
        if row["error"] is None:
            all_t, body_t = next(it)
            ids_all = {title_map[x] for x in all_t if x in title_map} - {row["page_id"]}
            ids_body = {title_map[x] for x in body_t if x in title_map} - {row["page_id"]}
            row["html_all"], row["body"] = len(ids_all), len(ids_body)
    df = pd.DataFrame(rows)
    df["template_share"] = 1 - df.body / df.html_all
    out = path(cfg, "generated")
    df.to_csv(out / "bias_check.csv", index=False)
    ok = df[df.error.isna()]
    summ = {"n_pages": len(df), "n_errors": int(df.error.notna().sum()), "removed_selectors": REMOVE}
    for grp, x in ok.groupby("group"):
        summ[grp] = {
            "n": int(len(x)),
            "median_dump_out_degree": float(x.dump_out_degree.median()),
            "median_html_all": float(x.html_all.median()),
            "median_body": float(x.body.median()),
            "median_template_share": float(x.template_share.median()),
            "mean_template_share": float(x.template_share.mean()),
            "median_ratio_html_all_to_dump": float((x.html_all / x.dump_out_degree.replace(0, np.nan)).median()),
        }
    # does removing templates change who is on top?
    t = ok[ok.group == "top_out_degree"]
    from scipy.stats import spearmanr
    rho, p = spearmanr(t.dump_out_degree, t.body)
    summ["top_group_spearman_dump_vs_body"] = {"rho": float(rho), "p_value": float(p), "n": int(len(t))}
    write_json(summ, out / "bias_check.json")
    log.info("bias check: %s", summ)


if __name__ == "__main__":
    main()
